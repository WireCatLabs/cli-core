// What a national number may start with before its significant digits: Belarus dials `8 0…`, Lithuania `0` or
// `8`. Alternatives with a capturing group rewrite the number (a carrier code) and are left out. Without a prefix
// the library answers 0, not a string.
const trunkOf = (parsing: string | undefined, prefix: unknown): string =>
  typeof parsing === "string"
    ? alternatives(parsing)
        .filter((one) => !one.includes("("))
        .join("|")
    : typeof prefix === "string"
      ? prefix
      : ""

const alternatives = (pattern: string): string[] => {
  const parts = [""]
  let depth = 0
  for (const char of pattern) {
    if (char === "(") depth++
    if (char === ")") depth--
    if (char === "|" && depth === 0) parts.push("")
    else parts[parts.length - 1] += char
  }
  return parts
}

const metadata = new Metadata()
const rows = COUNTRIES.map((country) => {
  metadata.selectNumberingPlan(country)
  const plan = metadata.numberingPlan
  const mobile = plan.type("MOBILE")?.pattern()
  return {
    country: country.toLowerCase(),
    code: metadata.countryCallingCode(),
    trunk: trunkOf(plan.nationalPrefixForParsing(), plan.nationalPrefix()),
    lengths: plan.possibleLengths(),
    valid: plan.nationalNumberPattern(),
    // North America has no separate mobile range: every number is fixed line or mobile.
    mobile: mobile && mobile !== plan.type("FIXED_LINE")?.pattern() ? mobile : null,
  }
})

const header =
  "// Generated by scripts/phone-plans.ts from libphonenumber-js metadata; do not edit by hand.\n" +
  "// valid and mobile match a national number: the digits after the country code, the trunk prefix dropped.\n"
writeFileSync(
  new URL("../src/domain/phone-plans.generated.ts", import.meta.url),
  `${header}export const PHONE_PLANS = ${JSON.stringify(rows, null, 2)} as const\n`,
)
console.log(`${rows.length} plans`)
