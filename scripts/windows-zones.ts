// Writes src/calendar/windows-zones.generated.ts from CLDR's windowsZones.xml: each Windows time zone name and the
// IANA zone of its "001" (world) territory, the one CLDR says to use when the country is unknown.
// Run: node --experimental-strip-types scripts/windows-zones.ts [release-tag] && pnpm exec biome check --write src/calendar/windows-zones.generated.ts
import { writeFileSync } from "node:fs"

const tag = process.argv[2] ?? "release-49"
const source = `https://raw.githubusercontent.com/unicode-org/cldr/${tag}/common/supplemental/windowsZones.xml`

const response = await fetch(source)
if (!response.ok) throw new Error(`${source}: HTTP ${response.status}`)
const xml = await response.text()

const zones = new Map<string, string>()
for (const [, attributes = ""] of xml.matchAll(/<mapZone\s([^>]*)\/>/gu)) {
  const attribute = (name: string) => new RegExp(`\\b${name}="([^"]*)"`, "u").exec(attributes)?.[1]
  const windows = attribute("other")
  const iana = attribute("type")
  if (attribute("territory") !== "001" || !windows || !iana) continue
  zones.set(windows, iana)
}
if (zones.size < 100) throw new Error(`${source}: only ${zones.size} world zones, expected about 140`)

const rows = [...zones]
  .sort(([a], [b]) => a.localeCompare(b, "en"))
  .map(([w, i]) => `  ${JSON.stringify(w)}: ${JSON.stringify(i)},`)
writeFileSync(
  new URL("../src/calendar/windows-zones.generated.ts", import.meta.url),
  [
    `// Generated by scripts/windows-zones.ts from CLDR ${tag} (Unicode License v3, THIRD_PARTY_NOTICES); do not edit by hand.`,
    `// ${source}`,
    "export const WINDOWS_ZONES: Readonly<Record<string, string>> = {",
    ...rows,
    "}",
    "",
  ].join("\n"),
)
console.log(`${zones.size} Windows zones from CLDR ${tag}`)
