// Writes src/domain/free-mail-domains.generated.ts: mailbox providers anyone can sign up to, from microlink's
// free-email-domains (MIT), pinned to a release. Run at release, like scripts/organization-sectors.ts.
// Run: node --experimental-strip-types scripts/free-mail-domains.ts && pnpm exec biome check --write src/domain/free-mail-domains.generated.ts
import { writeFileSync } from "node:fs"
import { getDomain } from "tldts"
import { SECTOR_DOMAINS } from "../src/domain/organization-sectors.generated.ts"

const VERSION = "v1.16.15"
const URL_ = `https://raw.githubusercontent.com/microlinkhq/free-email-domains/${VERSION}/domains.json`
const OUT = new URL("../src/domain/free-mail-domains.generated.ts", import.meta.url)

const response = await fetch(URL_, { signal: AbortSignal.timeout(60_000) })
if (!response.ok) throw new Error(`free-email-domains answered ${response.status}`)
const listed = (await response.json()) as string[]

// A provider that is also an organization of the Wikidata table (facebook.com, sky.com, orange.fr) sends its own bills
// and notices from that domain: the organization wins, or its mail would never find it.
const organizations = new Set(Object.values(SECTOR_DOMAINS).flatMap((domains) => domains.split(" ")))
// Only registrable domains, as `registrableOf` reads mail: a host under dynv6.net never matches a sender.
const registrable = [...new Set(listed.map((one) => one.trim().toLowerCase()))].filter((one) => getDomain(one) === one)
const kept = registrable.filter((one) => !organizations.has(one)).sort()

writeFileSync(
  OUT,
  `// Generated by scripts/free-mail-domains.ts from microlinkhq/free-email-domains ${VERSION}; do not edit by hand.\n` +
    "// free-email-domains is MIT, Copyright (c) 2017 Microlink (https://github.com/microlinkhq/free-email-domains).\n" +
    "// Registrable domains only, less those the Wikidata sector table holds; sorted, one space between.\n" +
    `export const FREE_MAIL_DOMAINS = "${kept.join(" ")}"\n`,
)
console.error(
  `${listed.length} listed, ${registrable.length} registrable, ${registrable.length - kept.length} left to Wikidata, ` +
    `${kept.length} kept`,
)
