import { CliError } from "@wirecat/cli-base"
import type { CacheDatabase } from "./driver.js"
import { lockedOutNotice, recordClient, refusalAdvice, storeClients } from "./sqlite/clients.js"
import { generatedMigrations } from "./sqlite/manifest.js"

export interface Migration {
  version: number
  /** The oldest schema version whose statements still work on a file at this version. */
  minCompatible: number
  statements: string[]
  /** Runs before the statements, inside the same transaction. */
  before?: (database: CacheDatabase, now: () => number) => void
}

/**
 * Every migration is generated by drizzle-kit and numbered in `sqlite/manifest.ts`. Version 1 creates the whole
 * schema. **A migration that has reached anyone's file is never edited.** After it: forward-only and additive —
 * no `DROP` and no rebuild of a base table, a new column is nullable or has a default, and every `INSERT` in the
 * store names its columns — so an older `tg` keeps writing to a file a newer `max` has migrated. Only a breaking
 * change raises `minCompatible`, and that is a major version of this package. The search indexes are derived and
 * may be dropped and rebuilt. Every version after the first gets a `version-N.test.ts` that opens a file at N-1.
 *
 * Times are epoch milliseconds: an integer sorts and ranges without a format to agree on.
 */
export const MIGRATIONS: Migration[] = generatedMigrations()

const HISTORY = `CREATE TABLE IF NOT EXISTS schema_migrations (
  version        INTEGER PRIMARY KEY,
  min_compatible INTEGER NOT NULL,
  applied_at     INTEGER NOT NULL
)`

const latest = (migrations: Migration[]): number => migrations.at(-1)?.version ?? 0

/**
 * The pre-rename `cli-messaging` store also has `schema_migrations`, with its own, higher numbers ("29, needs at
 * least 28"). Once ours caught up, the version check alone took it for a compatible file, opened it and would have
 * migrated it. Version 1 here always creates `meetings`; that store never had one.
 */
const OWN_TABLE = "meetings"
const hasTable = (database: CacheDatabase, name: string): boolean =>
  database.prepare("SELECT 1 AS found FROM sqlite_master WHERE type = 'table' AND name = ?").get(name) !== undefined

const fileState = (database: CacheDatabase): { version: number; minCompatible: number } => {
  const row = database
    .prepare("SELECT version, min_compatible FROM schema_migrations ORDER BY version DESC LIMIT 1")
    .get()
  return { version: Number(row?.version ?? 0), minCompatible: Number(row?.min_compatible ?? 0) }
}

/**
 * Brings the file up to this version, or opens a newer one it can still write to, or refuses.
 * Inside `BEGIN IMMEDIATE`, so two processes opening an old file at once migrate it once. A migration
 * that fails names `store reset` when the app has one: without it the owner is stuck until a build that can migrate
 * the file. An app without that command (drive) passes no `command`, and the advice names none.
 */
export const migrate = (
  database: CacheDatabase,
  {
    migrations = MIGRATIONS,
    now = Date.now,
    command,
    version,
    ownTable = OWN_TABLE,
  }: {
    migrations?: Migration[]
    now?: () => number
    command?: string
    /** The CLI's own version: with `command`, it is recorded so a later upgrade can name who it locks out. */
    version?: string
    ownTable?: string | null
  } = {},
): string | undefined => {
  const ours = latest(migrations)
  database.exec("BEGIN IMMEDIATE")
  try {
    database.exec(HISTORY)
    const file = fileState(database)
    if (file.version > 0 && ownTable !== null && !hasTable(database, ownTable)) {
      throw new CliError(
        "configuration_error",
        `the message store was written by another, incompatible tool (schema ${file.version} by its own numbering, ` +
          "with no meetings table) — this tool will not open or change it; move it aside to start a new store",
      )
    }
    if (file.version > ours && file.minCompatible > ours) {
      throw new CliError(
        "configuration_error",
        `the message store was written by a newer version (schema ${file.version}, needs at least ` +
          `${file.minCompatible}; this one speaks ${ours}) — ${refusalAdvice(storeClients(database), command, file.version)}`,
      )
    }
    const raisedTo = migrations
      .filter((migration) => migration.version > file.version)
      .reduce((highest, { minCompatible }) => Math.max(highest, minCompatible), file.minCompatible)
    const notice =
      file.version > 0 && raisedTo > file.minCompatible
        ? lockedOutNotice(storeClients(database), {
            ...(command ? { command } : {}),
            schema: ours,
            minCompatible: raisedTo,
          })
        : undefined
    for (const migration of migrations) {
      if (migration.version <= file.version) continue
      migration.before?.(database, now)
      for (const statement of migration.statements) database.exec(statement)
      database
        .prepare("INSERT INTO schema_migrations (version, min_compatible, applied_at) VALUES (?, ?, ?)")
        .run(migration.version, migration.minCompatible, now())
    }
    if (command && version) recordClient(database, { command, version, speaks: ours }, now())
    database.exec("COMMIT")
    return notice
  } catch (error) {
    database.exec("ROLLBACK")
    if (error instanceof CliError) throw error
    const cause = error instanceof Error ? error.message : String(error)
    throw new CliError(
      "configuration_error",
      `the message store could not be brought up to schema ${ours}: ${cause}. ` +
        (command
          ? `\`${command} store reset\` takes a backup of it first, then starts an empty store`
          : "moving the file aside keeps it as a backup and starts an empty store"),
      { cause },
    )
  }
}
