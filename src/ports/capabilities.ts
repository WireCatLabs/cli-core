import type { ProviderDescription } from "./provider.js"

/** Defaults preserve the command surface of existing provider descriptions. */
export const commandCapabilities = (provider: ProviderDescription) => ({
  fileBackedUploads: provider.fileBackedUploads === true,
  topics: provider.topics !== false,
  topicOptions: {
    list: provider.topicOptions?.list ?? provider.topics !== false,
    send: provider.topicOptions?.send ?? provider.topics !== false,
    markRead: provider.topicOptions?.markRead ?? provider.topics !== false,
    pollCreate: provider.topicOptions?.pollCreate ?? provider.topics !== false,
  },
  comments: provider.comments !== false,
  commaSeparatedMessageIds: provider.commaSeparatedMessageIds === true,
  forwardTopic: provider.topics !== false && provider.forwardTopic === true,
  spoiler: provider.mediaOptions?.includes("spoiler") === true,
  captionAbove: provider.mediaOptions?.includes("captionAbove") === true,
  fileName: provider.mediaOptions?.includes("fileName") === true,
  html: provider.html === true,
  stickers: provider.stickers === true,
  pollQuiz: provider.pollQuiz === true,
  pollVoters: provider.pollVoters === true,
  topicShow: provider.topicShow === true,
  folderRules: provider.folderRules === true,
  groupPhoto: provider.groupPhoto === true,
  chatMedia: provider.chatMedia === true,
  privacy: provider.privacy === true,
  chatMute: provider.chatMute === true,
  chatDeletion: provider.chatDeletion === true,
  personalBots: provider.personalBots === true,
  inviteLinkUpdate: provider.inviteLinkUpdate === true,
  officialStats: provider.officialStats === true,
  folderOrder: provider.folderOrder !== false,
  folderJoin: provider.folderJoin !== false,
  inviteLinkList: provider.inviteLinkList !== false,
  inviteLinkRevoke: provider.inviteLinkRevoke !== false,
  knowsAccountAge: provider.knowsAccountAge !== false,
  addsWithHistory: provider.addsWithHistory !== false,
  tracksMembers: provider.tracksMembers !== false,
})
